conn = sqlite3.connect(DB, timeout=30)
c = conn.cursor()

wb = openpyxl.load_workbook(XLS, read_only=True)
ws = wb.active

updated = 0
for row in ws.iter_rows(min_row=6, values_only=True):
    rn = str(row[0] or '').strip()
    sc = str(row[3] or '').strip()
    if not rn or not sc:
        continue
    m = re.match(r'(\d{2}\.\d{2})', sc)
    if not m:
        continue
    cat = CLASS_MAP.get(m.group(1))
    if cat:
        c.execute("UPDATE russian_components SET category=? WHERE registry='mintsifry' AND registry_id=?",
                  (cat, rn))
        if c.rowcount > 0:
            updated += 1

conn.commit()
wb.close()

print(f'Updated: {updated:,}')
