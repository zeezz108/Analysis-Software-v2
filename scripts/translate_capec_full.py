def main():
    conn = sqlite3.connect(DB_PATH)
    c = conn.cursor()

    # Вставляем ручные переводы
    for cid, ru in MANUAL.items():
        c.execute("UPDATE capec_entries SET name_ru = ? WHERE capec_id = ?", (ru, cid))

    conn.commit()

    # Статистика
    c.execute("SELECT COUNT(*) FROM capec_entries")
    total = c.fetchone()[0]
    c.execute("SELECT COUNT(*) FROM capec_entries WHERE name_ru IS NOT NULL AND name_ru != ''")
    has_ru = c.fetchone()[0]
    c.execute("SELECT COUNT(*) FROM capec_entries WHERE name_ru IS NULL OR name_ru = ''")
    no_ru = c.fetchone()[0]

    print(f"Всего: {total}")
    print(f"Переведено: {has_ru}")
    print(f"Без перевода: {no_ru}")

    if no_ru > 0:
        c.execute("SELECT capec_id, name FROM capec_entries WHERE name_ru IS NULL OR name_ru = '' LIMIT 10")
        print("\nОсталось без перевода:")
        for r in c.fetchall():
            print(f"  CAPEC-{r[0]}: {r[1]}")

    conn.close()


if __name__ == "__main__":
    main()
